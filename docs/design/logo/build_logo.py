"""Generates every Orbit logo asset from one geometry. Run from the repo root with `python3 -I`."""
import json, math, os, subprocess, sys, tempfile
NAVY, PERIWINKLE, LIME = '#0E1230', '#86B6FF', '#D4F26E'
CHROME = '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome'
R, SW, CR, SR, GAP = 14, 3.4, 6.2, 4.2, 2.2
half = math.degrees(2 * math.asin((SR + GAP + SW / 2) / (2 * R)))
pt = lambda a: (20 + R * math.cos(math.radians(a)), 20 + R * math.sin(math.radians(a)))
(x0, y0), (x1, y1), (sx, sy) = pt(-45 + half), pt(-45 - half), pt(-45)
ARC = f'M{x0:.3f},{y0:.3f}A{R},{R} 0,1 1 {x1:.3f},{y1:.3f}'
CORE = f'M{20 - CR:.3f},20a{CR},{CR} 0,1 1 {2 * CR},0a{CR},{CR} 0,1 1 {-2 * CR},0'
SAT = f'M{sx - SR:.3f},{sy:.3f}a{SR},{SR} 0,1 1 {2 * SR},0a{SR},{SR} 0,1 1 {-2 * SR},0'

def vector(size, viewport, ring, core, sat, comment=None, group=None):
    head = f'<!-- {comment} -->\n' if comment else ''
    g0, g1, pad = '', '', '    '
    if group:
        g0, g1, pad = f'    <group android:scaleX="{group[0]}" android:scaleY="{group[0]}" android:translateX="{group[1]}" android:translateY="{group[1]}">\n', '    </group>\n', '        '
    return f'''{head}<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="{size}dp"
    android:height="{size}dp"
    android:viewportWidth="{viewport}"
    android:viewportHeight="{viewport}">
{g0}{pad}<path
{pad}    android:strokeColor="{ring}"
{pad}    android:strokeWidth="{SW}"
{pad}    android:strokeLineCap="round"
{pad}    android:pathData="{ARC}" />
{pad}<path
{pad}    android:fillColor="{core}"
{pad}    android:pathData="{CORE}" />
{pad}<path
{pad}    android:fillColor="{sat}"
{pad}    android:pathData="{SAT}" />
{g1}</vector>
'''

def write(path, text):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    open(path, 'w').write(text)

COMPOSE = 'shared/src/commonMain/composeResources/drawable'
write(f'{COMPOSE}/ic_orbit.xml', vector(32, 40, '#FF000000', '#FF000000', '#FF000000', 'The Orbit mark in one colour, tinted at runtime. Generated by docs/design/logo/build_logo.py.'))
write(f'{COMPOSE}/orbit_brand.xml', vector(120, 40, 'FF', 'FF', 'FF', 'The Orbit mark in its brand colours, for the startup screen.').replace('"FF"', '@@'))
s = open(f'{COMPOSE}/orbit_brand.xml').read()
parts = s.split('@@')
open(f'{COMPOSE}/orbit_brand.xml', 'w').write(parts[0] + f'"{("#FF" + PERIWINKLE[1:])}"' + parts[1] + f'"{("#FF" + PERIWINKLE[1:])}"' + parts[2] + f'"{("#FF" + LIME[1:])}"' + parts[3])

# Adaptive icon: 108dp canvas, the mark inside the 66dp safe zone.
SCALE, MOVE = 1.35, 27.0
RES = 'androidApp/src/main/res'
write(f'{RES}/drawable-v24/ic_launcher_foreground.xml', vector(108, 108, PERIWINKLE, PERIWINKLE, LIME, group=(SCALE, MOVE)))
write(f'{RES}/drawable/ic_launcher_monochrome.xml', vector(108, 108, '#FFFFFF', '#FFFFFF', '#FFFFFF', group=(SCALE, MOVE)))
write(f'{RES}/drawable/ic_launcher_background.xml', f'''<?xml version="1.0" encoding="utf-8"?>
<vector xmlns:android="http://schemas.android.com/apk/res/android"
    android:width="108dp"
    android:height="108dp"
    android:viewportWidth="108"
    android:viewportHeight="108">
    <path
        android:fillColor="{NAVY}"
        android:pathData="M0,0h108v108h-108z" />
</vector>
''')
for name in ('ic_launcher', 'ic_launcher_round'):
    write(f'{RES}/mipmap-anydpi-v26/{name}.xml', '''<?xml version="1.0" encoding="utf-8"?>
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@drawable/ic_launcher_background"/>
    <foreground android:drawable="@drawable/ic_launcher_foreground"/>
    <monochrome android:drawable="@drawable/ic_launcher_monochrome"/>
</adaptive-icon>
''')

def svg(px, bg, ring, core, sat, scale, radius=0):
    arc = ARC.replace(',', ' ')
    body = (f'<path d="{ARC}" fill="none" stroke="{ring}" stroke-width="{SW}" stroke-linecap="round"/>'
            f'<circle cx="20" cy="20" r="{CR}" fill="{core}"/><circle cx="{sx:.3f}" cy="{sy:.3f}" r="{SR}" fill="{sat}"/>')
    rect = f'<rect width="40" height="40" rx="{radius}" fill="{bg}"/>' if bg else ''
    return (f'<!doctype html><html><body style="margin:0;background:transparent"><svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 40 40" width="{px}" height="{px}" style="display:block">'
            f'{rect}<g transform="translate(20 20) scale({scale}) translate(-20 -20)">{body}</g></svg></body></html>')

def png(path, px, *a, **k):
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with tempfile.NamedTemporaryFile('w', suffix='.html', delete=False) as f:
        f.write(svg(px, *a, **k))
    subprocess.run([CHROME, '--headless=new', '--disable-gpu', '--hide-scrollbars', '--force-device-scale-factor=1',
                    '--default-background-color=00000000', f'--window-size={px},{px}', f'--screenshot={os.path.abspath(path)}', f'file://{f.name}'],
                   check=True, stderr=subprocess.DEVNULL, stdout=subprocess.DEVNULL)
    os.unlink(f.name)

for density, px in (('mdpi', 48), ('hdpi', 72), ('xhdpi', 96), ('xxhdpi', 144), ('xxxhdpi', 192)):
    png(f'{RES}/mipmap-{density}/ic_launcher.png', px, NAVY, PERIWINKLE, PERIWINKLE, LIME, .74, radius=9)
    png(f'{RES}/mipmap-{density}/ic_launcher_round.png', px, NAVY, PERIWINKLE, PERIWINKLE, LIME, .66, radius=20)

ASSETS = 'iosApp/iosApp/Assets.xcassets'
png(f'{ASSETS}/AppIcon.appiconset/app-icon-1024.png', 1024, NAVY, PERIWINKLE, PERIWINKLE, LIME, .74)
png(f'{ASSETS}/AppIcon.appiconset/app-icon-1024-dark.png', 1024, NAVY, PERIWINKLE, PERIWINKLE, LIME, .74)
png(f'{ASSETS}/AppIcon.appiconset/app-icon-1024-tinted.png', 1024, '#000000', '#FFFFFF', '#FFFFFF', '#FFFFFF', .74)
appicon = json.load(open(f'{ASSETS}/AppIcon.appiconset/Contents.json'))
for image in appicon['images']:
    look = next((a['value'] for a in image.get('appearances', [])), None)
    if look: image['filename'] = f'app-icon-1024-{look}.png'
write(f'{ASSETS}/AppIcon.appiconset/Contents.json', json.dumps(appicon, indent=2) + '\n')
for scale, suffix in ((1, ''), (2, '@2x'), (3, '@3x')):
    png(f'{ASSETS}/LaunchLogo.imageset/launch-logo{suffix}.png', 120 * scale, None, PERIWINKLE, PERIWINKLE, LIME, 1)
write(f'{ASSETS}/LaunchLogo.imageset/Contents.json', json.dumps({'images': [
    {'filename': 'launch-logo.png', 'idiom': 'universal', 'scale': '1x'},
    {'filename': 'launch-logo@2x.png', 'idiom': 'universal', 'scale': '2x'},
    {'filename': 'launch-logo@3x.png', 'idiom': 'universal', 'scale': '3x'}], 'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n')
rgb = lambda h: {c: f'0x{h[i:i + 2]}' for c, i in (('red', 1), ('green', 3), ('blue', 5))}
write(f'{ASSETS}/LaunchBackground.colorset/Contents.json', json.dumps({'colors': [{'idiom': 'universal', 'color': {'color-space': 'srgb', 'components': {'alpha': '1.000', **rgb(NAVY)}}}], 'info': {'author': 'xcode', 'version': 1}}, indent=2) + '\n')
